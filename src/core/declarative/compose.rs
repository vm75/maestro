    #[tokio::test]
    async fn test_compose_provider_lifecycle() {
        let temp = tempfile::tempdir().unwrap();
        fs::set_permissions(temp.path(), fs::Permissions::from_mode(0o700)).unwrap();
        let provider = ComposeProvider::new(
            "docker",
            PathBuf::from("/bin/docker"),
            temp.path().to_path_buf(),
            temp.path().to_path_buf(),
            CommandRunner::new(true),
        );
        let change = Change {
            resource: "service/myapp".to_string(),
            backend: "docker/compose".to_string(),
            operation: Operation::Create,
            before: None,
            after: Some("a".repeat(64)),
        };
        let mut config = Config::default();
        config.services.insert(
            "myapp".to_string(),
            Service {
                name: "My App".to_string(),
                backend: "compose".to_string(),
                engine: "docker".to_string(),
                enabled: true,
                containers: BTreeMap::from([(
                    "app".to_string(),
                    Container {
                        image: "alpine".to_string(),
                        ..Default::default()
                    },
                )]),
                ..Default::default()
            },
        );
        provider
            .preflight(&change, &Config::default(), &config)
            .await
            .unwrap();
        provider
            .apply(&change, &Config::default(), &config)
            .await
            .unwrap();
        assert!(temp.path().join("myapp/compose.yaml").exists());
        assert!(
            provider
                .action("myapp", "restart")
                .await
                .unwrap()
                .starts_with("SIMULATED:")
        );
        assert!(
            provider
                .logs("myapp", 10)
                .await
                .unwrap()
                .starts_with("SIMULATED:")
        );
        assert!(provider.action("myapp", "invalid").await.is_err());
        assert!(provider.logs("missing", 10).await.is_err());

        let obs = provider
            .observe(&change, &Config::default(), &config)
            .await
            .unwrap();
        assert_eq!(obs, ObservedResource::After);

        let file = temp.path().join("myapp/compose.yaml");
        let original = fs::read(&file).unwrap();
        let sibling = temp.path().join("myapp/operator-notes");
        fs::write(&sibling, b"keep").unwrap();
        let remove_change = Change {
            resource: "service/myapp".to_string(),
            backend: "docker/compose".to_string(),
            operation: Operation::Remove,
            before: Some("a".repeat(64)),
            after: None,
        };
        let mut edited = original.clone();
        edited.extend_from_slice(b"# local edit\n");
        fs::write(&file, edited).unwrap();
        assert_eq!(
            provider
                .observe(&remove_change, &config, &Config::default())
                .await
                .unwrap(),
            ObservedResource::Unknown
        );
        assert!(
            provider
                .apply(&remove_change, &config, &Config::default())
                .await
                .is_err()
        );
        fs::remove_file(&file).unwrap();
        std::os::unix::fs::symlink(&sibling, &file).unwrap();
        assert!(
            provider
                .apply(&remove_change, &config, &Config::default())
                .await
                .is_err()
        );
        fs::remove_file(&file).unwrap();
        fs::write(&file, original).unwrap();
        fs::set_permissions(&file, fs::Permissions::from_mode(0o600)).unwrap();
        provider
            .apply(&remove_change, &config, &Config::default())
            .await
            .unwrap();
        assert!(!file.exists());
        assert_eq!(fs::read(&sibling).unwrap(), b"keep");
    }

// Direct translation of Server Man container_options.go for the common
// Compose model. Explicit advanced options remain typed, never raw argv.
fn validate_options(service: &Service) -> Result<()> {
    use regex::Regex;
    let identity = Regex::new(r"^(?:[a-zA-Z_][a-zA-Z0-9_.-]*|[0-9]+)$")?;
    let native_name = Regex::new(r"^[a-zA-Z0-9][a-zA-Z0-9_.-]{0,127}$")?;
    let namespace = Regex::new(r"^(keep-id(:uid=[0-9]+(,gid=[0-9]+)?)?|host|private|auto|nomap)$")?;
    let mapping = Regex::new(r"^[0-9]+:[0-9]+:[1-9][0-9]*$")?;
    let capability = Regex::new(r"^(ALL|[A-Z][A-Z0-9_]*)$")?;
    let size = Regex::new(r"^[0-9]+([kKmMgGtT][bB]?)?$")?;
    let env_name = Regex::new(r"^[A-Za-z_][A-Za-z0-9_]*$")?;
    let literal = |s: &str| !s.chars().any(char::is_control);
    let path = |s: &str| super::path_valid(s,true) && !s.contains(['\0','\r','\n',':']);
    for (name,v) in &service.containers {
        ensure!(v.container_name.is_empty() || native_name.is_match(&v.container_name),"invalid container {name} container_name");
        ensure!(v.entrypoint.len()<=32 && v.devices.len()<=32 && v.tmpfs.len()<=32
            && v.depends_on.len()<=32 && v.uid_maps.len()<=64 && v.gid_maps.len()<=64
            && v.security_opt.len()<=32 && v.log_options.len()<=32,"invalid container {name} option count");
        ensure!(v.user.is_empty() || (v.user.split(':').count()<=2 && v.user.split(':').all(|part|identity.is_match(part))),"invalid container {name} user");
        ensure!(v.userns_mode.is_empty() || (namespace.is_match(&v.userns_mode) && v.uid_maps.is_empty() && v.gid_maps.is_empty()),"invalid container {name} user namespace");
        ensure!(v.uid_maps.iter().chain(&v.gid_maps).all(|m|mapping.is_match(m)),"invalid container {name} UID/GID mapping");
        ensure!(service.engine!="docker" || (v.uid_maps.is_empty() && v.gid_maps.is_empty() && v.userns_mode!="nomap" && !v.userns_mode.starts_with("keep-id")),"Podman user namespace settings require Podman");
        ensure!(v.group_add.iter().all(|g|if g=="keep-groups"{service.engine=="podman"}else{identity.is_match(g)}),"invalid container {name} group_add");
        ensure!(matches!(v.network_mode.as_str(),""|"host"|"none") || v.network_mode.strip_prefix("service:").is_some_and(|peer|peer!=name.as_str()&&service.containers.contains_key(peer)&&v.ports.is_empty()),"invalid container {name} network_mode");
        for device in &v.devices {
            let parts:Vec<_>=device.split(':').collect();
            ensure!(parts.len()<=3 && path(parts[0]) && (parts.len()<2||path(parts[1]))
                && (parts.len()<3||(!parts[2].is_empty()&&parts[2].bytes().all(|c|b"rwm".contains(&c)))),"invalid container {name} device");
        }
        ensure!(v.cap_add.iter().chain(&v.cap_drop).all(|c|capability.is_match(c)),"invalid container {name} capability");
        ensure!(v.security_opt.iter().all(|s|matches!(s.as_str(),"no-new-privileges"|"no-new-privileges:true"|"no-new-privileges:false"|"label=disable"|"seccomp=unconfined"|"seccomp:unconfined")),"invalid container {name} security_opt");
        ensure!(v.tmpfs.iter().all(|s|path(s.split(':').next().unwrap_or(""))&&!s.contains(['\0','\r','\n',' ','\t'])),"invalid container {name} tmpfs");
        ensure!(v.working_dir.is_empty()||path(&v.working_dir),"invalid container {name} working_dir");
        ensure!(v.entrypoint.iter().all(|s|literal(s)&&s.len()<=8192),"invalid container {name} entrypoint");
        ensure!(v.command.iter().all(|s|!s.contains('\0')&&s.len()<=8192),"invalid container {name} command");
        ensure!(v.environment.iter().all(|(k,v)|env_name.is_match(k)&&!v.contains('\0')&&v.len()<=8192),"invalid container {name} environment");
        ensure!(v.shm_size.is_empty()||size.is_match(&v.shm_size),"invalid container {name} shm_size");
        ensure!(super::container_health::duration(&v.stop_grace_period),"invalid container {name} stop_grace_period");
        ensure!(matches!(v.pull_policy.as_str(),""|"missing"|"always"|"never"|"newer"),"invalid container {name} pull_policy");
        ensure!(matches!(v.restart.as_str(),""|"no"),"Compose restart supervision is not supported with independent boot enablement; use Quadlet or omit restart");
        ensure!(matches!(v.log_driver.as_str(),""|"k8s-file"|"journald"|"none"|"passthrough"|"passthrough-tty"),"invalid container {name} log_driver");
        ensure!(v.log_options.iter().all(|(k,v)|env_name.is_match(&k.replace('-',"_" ))&&literal(v)&&v.len()<=4096),"invalid container {name} log_options");
        for mount in &v.mounts {
            ensure!(matches!(mount.selinux.as_str(),""|"private"|"shared"|"z"|"Z")&&(!mount.chown||service.engine=="podman"),"invalid container {name} mount options");
        }
    }
    // Include shared-network namespace edges in the same dependency cycle test.
    fn visit<'a>(service: &'a Service,name: &'a str,visiting: &mut std::collections::BTreeSet<&'a str>,done: &mut std::collections::BTreeSet<&'a str>) -> Result<()> {
        if done.contains(name){return Ok(())}
        ensure!(visiting.insert(name),"container dependency cycle");
        let container=service.containers.get(name).ok_or_else(||anyhow!("unknown container dependency"))?;
        for dep in container.depends_on.keys(){visit(service,dep,visiting,done)?;}
        if let Some(peer)=container.network_mode.strip_prefix("service:"){visit(service,peer,visiting,done)?;}
        visiting.remove(name);done.insert(name);Ok(())
    }
    let mut visiting=std::collections::BTreeSet::new();let mut done=std::collections::BTreeSet::new();
    for name in service.containers.keys(){visit(service,name,&mut visiting,&mut done)?;}
    Ok(())
}

fn render_compose(
    config: &Config,
    id: &str,
    fingerprint: &str,
    storage_base: &Path,
) -> Result<String> {
    use serde_json::{Value, json};

    ensure!(
        super::id_valid(id) && store::valid_revision(fingerprint),
        "invalid Compose resource identity"
    );
    ensure!(
        storage_base.is_absolute(),
        "Compose storage base must be absolute"
    );
    let service = config
        .services
        .get(id)
        .ok_or_else(|| anyhow!("missing Compose service"))?;
    super::container_health::validate(&service.containers)?;
    validate_options(service)?;
    let mut services = BTreeMap::new();
    let literal = |value: &str| value.replace('$', "$$");
    let words = |values: &[String]| {
        values
            .iter()
            .map(|value| literal(value))
            .collect::<Vec<_>>()
    };
    let path_value = |path: &Path| -> Result<String> {
        let path = path
            .to_str()
            .ok_or_else(|| anyhow!("non-UTF-8 Compose path"))?;
        ensure!(
            !path.chars().any(char::is_control),
            "invalid Compose path characters"
        );
        Ok(literal(path))
    };
    for (name, container) in &service.containers {
        ensure!(super::id_valid(name), "invalid Compose container ID");
        let mut definition = serde_json::Map::new();
        let native_name = if container.container_name.is_empty() {
            format!("maestro-{id}-{name}")
        } else {
            container.container_name.clone()
        };
        definition.insert("image".into(), json!(literal(&container.image)));
        definition.insert("container_name".into(), json!(literal(&native_name)));
        definition.insert("labels".into(), json!({
            "io.server-man.service": id, "io.server-man.container": name, "io.server-man.fingerprint": fingerprint,
        }));
        // Systemd owns boot policy; the engine must not restart a stopped
        // project just because the host/daemon was restarted.
        definition.insert("restart".into(), json!("no"));
        let mut no_new_privileges = !container.privileged;
        for option in &container.security_opt {
            match option.as_str() {
                "no-new-privileges" | "no-new-privileges:true" => no_new_privileges = true,
                "no-new-privileges:false" => no_new_privileges = false,
                _ => {}
            }
        }
        let mut security = Vec::new();
        if no_new_privileges { security.push("no-new-privileges:true".to_owned()); }
        security.extend(container.security_opt.iter().filter(|value| !value.starts_with("no-new-privileges")).cloned());
        definition.insert("security_opt".into(), json!(words(&security)));
        for (field, values) in [
            ("ports", &container.ports),
            ("command", &container.command),
            ("entrypoint", &container.entrypoint),
            ("group_add", &container.group_add),
            ("devices", &container.devices),
            ("cap_add", &container.cap_add),
            ("x-podman.uidmaps", &container.uid_maps),
            ("x-podman.gidmaps", &container.gid_maps),
            ("cap_drop", &container.cap_drop),
            ("tmpfs", &container.tmpfs),
        ] {
            if !values.is_empty() {
                definition.insert(field.into(), json!(words(values)));
            }
        }
        for (field, value) in [
            ("working_dir", &container.working_dir),
            ("user", &container.user),
            ("userns_mode", &container.userns_mode),
            ("network_mode", &container.network_mode),
            ("shm_size", &container.shm_size),
            ("stop_grace_period", &container.stop_grace_period),
            ("pull_policy", &container.pull_policy),
        ] {
            if !value.is_empty() {
                definition.insert(field.into(), json!(literal(value)));
            }
        }
        for (field, enabled) in [
            ("privileged", container.privileged),
            ("read_only", container.read_only),
            ("init", container.init),
            ("tty", container.tty),
        ] {
            if enabled {
                definition.insert(field.into(), json!(true));
            }
        }
        if container.memory_mib > 0 {
            definition.insert(
                "mem_limit".into(),
                json!(format!("{}m", container.memory_mib)),
            );
        }
        if container.cpus > 0 {
            definition.insert("cpus".into(), json!(container.cpus));
        }
        if !container.log_driver.is_empty() || !container.log_options.is_empty() {
            ensure!(
                !container.log_driver.is_empty(),
                "Compose log options require a driver"
            );
            let options: BTreeMap<_, _> = container
                .log_options
                .iter()
                .map(|(key, value)| (key, literal(value)))
                .collect();
            definition.insert(
                "logging".into(),
                json!({"driver": literal(&container.log_driver), "options": options}),
            );
        }
        if !container.depends_on.is_empty() {
            let mut dependencies = BTreeMap::new();
            for (member, condition) in &container.depends_on {
                ensure!(
                    service.containers.contains_key(member),
                    "unknown Compose dependency"
                );
                ensure!(
                    matches!(condition.as_str(), "started" | "healthy"),
                    "unsupported Compose dependency condition"
                );
                dependencies.insert(member, json!({"condition": format!("service_{condition}")}));
            }
            definition.insert("depends_on".into(), json!(dependencies));
        }
        if let Some(health) = &container.healthcheck {
            let mut value = serde_json::Map::new();
            value.insert("test".into(), json!(words(&health.test)));
            for (name, duration) in [
                ("interval", &health.interval),
                ("timeout", &health.timeout),
                ("start_period", &health.start_period),
            ] {
                if !duration.is_empty() {
                    value.insert(name.into(), json!(duration));
                }
            }
            if health.retries != 0 {
                value.insert("retries".into(), json!(health.retries));
            }
            definition.insert("healthcheck".into(), json!(value));
        }
        if !container.environment.is_empty() {
            let values: BTreeMap<_, _> = container
                .environment
                .iter()
                .map(|(key, value)| (key, literal(value)))
                .collect();
            definition.insert("environment".into(), json!(values));
        }
        if !container.env_files.is_empty() {
            let paths = container
                .env_files
                .iter()
                .map(|id| {
                    let path = config
                        .secrets
                        .get(id)
                        .ok_or_else(|| anyhow!("missing Compose private file reference"))?;
                    ensure!(
                        super::path_valid(path, false),
                        "invalid Compose private file path"
                    );
                    path_value(&storage_base.join(path))
                })
                .collect::<Result<Vec<_>>>()?;
            definition.insert("env_file".into(), json!(paths));
        }
        if !container.mounts.is_empty() {
            let volumes = container.mounts.iter().map(|mount| {
                let storage = config.storage.get(&mount.storage).ok_or_else(|| anyhow!("missing Compose storage reference"))?;
                ensure!(super::path_valid(&storage.path, storage.external)
                    && super::path_valid(&mount.target, true)
                    && (mount.path.is_empty() || super::path_valid(&mount.path, false))
                    && matches!(mount.kind.as_str(), "" | "bind"),
                    "unsupported Compose mount");
                let source = storage_base.join(&storage.path);
                let source = if mount.path.is_empty() { source } else { source.join(&mount.path) };
                if !mount.selinux.is_empty() || mount.chown {
                    let source = source.to_str().ok_or_else(||anyhow!("non-UTF-8 Compose path"))?;
                    ensure!(!source.contains(':')&&!mount.target.contains(':'),"SELinux or ownership mount path cannot be represented by Compose short syntax");
                    let mut options = vec![if mount.read_only {"ro"}else{"rw"}];
                    if mount.chown { options.push("U"); }
                    match mount.selinux.as_str() { "private"|"Z"=>options.push("Z"),"shared"|"z"=>options.push("z"),_=>{} }
                    return Ok(json!(literal(&format!("{source}:{}:{}",mount.target,options.join(",")))));
                }
                Ok(json!({"type": "bind", "source": path_value(&source)?, "target": literal(&mount.target),
                    "read_only": mount.read_only, "bind": {"create_host_path":false}}))
            }).collect::<Result<Vec<_>>>()?;
            definition.insert("volumes".into(), json!(volumes));
        }
        services.insert(name, Value::Object(definition));
    }
    let mut model = json!({"name":native::project(id),"services":services});
    if service.engine == "podman" { model["x-podman"] = json!({"in_pod":false}); }
    let yaml = serde_yaml::to_string(&model)?;
    Ok(format!(
        "{HEADER}\n# resource=service/{id}\n# fingerprint={fingerprint}\n\n{yaml}"
    ))
}

pub struct ComposeProvider {
    pub engine: String, // "docker" or "podman"
    pub binary: PathBuf,
    pub base_dir: PathBuf,
    storage_base: PathBuf,
    pub runner: CommandRunner,
    systemctl: PathBuf,
    unit_dir: PathBuf,
}

impl ComposeProvider {
    pub fn new(
        engine: &str,
        binary: PathBuf,
        base_dir: PathBuf,
        storage_base: PathBuf,
        runner: CommandRunner,
    ) -> Self {
        let unit_dir = base_dir.join(format!("{engine}-compose-units"));
        Self {
            engine: engine.to_string(),
            binary,
            base_dir,
            storage_base,
            runner,
            systemctl: "/usr/bin/systemctl".into(),
            unit_dir,
        }
    }

    pub fn native_paths(mut self, systemctl: PathBuf) -> Self {
        self.systemctl = systemctl;
        if !self.runner.is_test_mode() {
            self.unit_dir = self.base_dir.join(format!("{}-compose-units",self.engine));
            self.base_dir = self.base_dir.join(format!("{}-compose",self.engine));
        }
        self
    }

    pub fn matches(&self, service: &Service) -> bool {
        service.backend == "compose" && service.engine == self.engine
    }

    fn compose_file(&self, service_id: &str) -> PathBuf {
        self.base_dir.join(service_id).join("compose.yaml")
    }

    pub async fn action(&self, service_id: &str, action: &str) -> Result<String> {
        ensure!(self.runner.is_test_mode(),"native Compose actions require authoritative configuration");
        ensure!(super::id_valid(service_id) && self.compose_file(service_id).exists(),"unknown Compose service");
        ensure!(matches!(action,"start"|"stop"|"restart"),"unsupported Compose action");
        Ok(format!("SIMULATED: Compose {action} on {service_id}"))
    }

    pub async fn logs(&self, service_id: &str, tail: usize) -> Result<String> {
        ensure!(self.runner.is_test_mode(),"native Compose logs require authoritative configuration");
        ensure!(super::id_valid(service_id) && self.compose_file(service_id).exists(),"unknown Compose service");
        Ok(format!("SIMULATED: Compose logs for {service_id} (tail {tail})"))
    }
}

impl ComposeProvider {
    fn open_app(&self, id: &str, create: bool) -> Result<Option<File>> {
        ensure!(super::id_valid(id), "invalid Compose resource ID");
        if create {
            match fs::DirBuilder::new().mode(0o700).create(&self.base_dir) {
                Ok(()) => {}
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
                Err(error) => return Err(error.into()),
            }
        }
        let Some(base) = optional(store::open_directory(&self.base_dir))? else {
            return Ok(None);
        };
        if create {
            match unix_fs::mkdirat(&base, id, Mode::from_bits_truncate(0o700)) {
                Ok(()) => base.sync_all()?,
                Err(Errno::EXIST) => {}
                Err(error) => return Err(error.into()),
            }
        }
        optional(store::open_child_directory(&base, id))
    }

    fn definitions(
        &self,
        change: &Change,
        previous: &Config,
        desired: &Config,
    ) -> Result<Definitions> {
        let id = change.resource.strip_prefix("service/").unwrap_or_default();
        ensure!(
            super::id_valid(id) && change.backend == format!("{}/compose", self.engine),
            "resource belongs to another Compose provider"
        );
        let render = |config: &Config, fingerprint: Option<&str>| -> Result<Option<String>> {
            fingerprint
                .map(|fingerprint| {
                    let service = config
                        .services
                        .get(id)
                        .ok_or_else(|| anyhow!("missing Compose definition"))?;
                    ensure!(
                        self.matches(service),
                        "resource belongs to another Compose provider"
                    );
                    let contents = render_compose(config, id, fingerprint, &self.storage_base)?;
                    ensure!(
                        contents.len() <= super::MAX_CONFIG_BYTES,
                        "Compose file exceeds its size limit"
                    );
                    Ok(contents)
                })
                .transpose()
        };
        Ok(Definitions {
            before: render(previous, change.before.as_deref())?,
            after: render(desired, change.after.as_deref())?,
        })
    }

    fn read_definition(&self, id: &str) -> Result<Option<Vec<u8>>> {
        let Some(directory) = self.open_app(id, false)? else {
            return Ok(None);
        };
        read_definition(&directory)
    }
}

struct Definitions {
    before: Option<String>,
    after: Option<String>,
}

fn optional<T>(result: Result<T>) -> Result<Option<T>> {
    match result {
        Ok(value) => Ok(Some(value)),
        Err(error) if error.downcast_ref::<Errno>() == Some(&Errno::NOENT) => Ok(None),
        Err(error) => Err(error),
    }
}

fn read_definition(directory: &File) -> Result<Option<Vec<u8>>> {
    optional(store::read_private(
        directory,
        "compose.yaml",
        super::MAX_CONFIG_BYTES,
    ))
}

impl ApplyProvider for ComposeProvider {
    async fn preflight_mode(&self, change: &Change, previous: &Config, desired: &Config, mode: super::ApplyMode) -> Result<()> {
        if self.runner.is_test_mode() { self.preflight(change,previous,desired).await }
        else { self.native_preflight(change,previous,desired,mode).await }
    }
    async fn apply_mode(&self, change: &Change, previous: &Config, desired: &Config, mode: super::ApplyMode) -> Result<()> {
        if self.runner.is_test_mode() { self.apply(change,previous,desired).await }
        else { self.native_apply(change,previous,desired,mode).await }
    }
    async fn preflight(&self, change: &Change, previous: &Config, desired: &Config) -> Result<()> {
        if !self.runner.is_test_mode() {
            return self.native_preflight(change,previous,desired,super::ApplyMode::Now).await;
        }
        let definitions = self.definitions(change, previous, desired)?;
        let id = change.resource.trim_start_matches("service/");
        ensure!(
            self.read_definition(id)?.as_deref()
                == definitions.before.as_deref().map(str::as_bytes),
            "Compose file differs from the reviewed prior definition"
        );
        Ok(())
    }

    async fn apply(&self, change: &Change, previous: &Config, desired: &Config) -> Result<()> {
        if !self.runner.is_test_mode() {
            return self.native_apply(change,previous,desired,super::ApplyMode::Now).await;
        }
        self.preflight(change, previous, desired).await?;
        let definitions = self.definitions(change, previous, desired)?;
        let id = change.resource.trim_start_matches("service/");
        let directory = self
            .open_app(id, definitions.after.is_some())?
            .ok_or_else(|| anyhow!("missing Compose directory"))?;
        let directory = store::LockedDirectory::try_acquire(directory)?;
        ensure!(
            read_definition(&directory)?.as_deref()
                == definitions.before.as_deref().map(str::as_bytes),
            "Compose file changed during publication"
        );
        if let Some(contents) = definitions.after {
            store::publish(
                &directory,
                "compose.yaml",
                contents.as_bytes(),
                definitions.before.is_none(),
            )?;
        } else {
            unix_fs::unlinkat(&directory, "compose.yaml", AtFlags::empty())?;
            directory.sync_all()?;
        }
        Ok(())
    }
}

impl RecoveryProvider for ComposeProvider {
    async fn observe_mode(&self, change: &Change, previous: &Config, desired: &Config, mode: super::ApplyMode) -> Result<ObservedResource> {
        if self.runner.is_test_mode() { self.observe(change,previous,desired).await }
        else { self.native_observe(change,previous,desired,mode).await }
    }
    async fn observe(
        &self,
        change: &Change,
        previous: &Config,
        desired: &Config,
    ) -> Result<ObservedResource> {
        if !self.runner.is_test_mode() {
            return self.native_observe(change,previous,desired,super::ApplyMode::Now).await;
        }
        let definitions = self.definitions(change, previous, desired)?;
        let id = change.resource.trim_start_matches("service/");
        let current = self.read_definition(id)?;
        Ok(
            if current.as_deref() == definitions.after.as_deref().map(str::as_bytes) {
                ObservedResource::After
            } else if current.as_deref() == definitions.before.as_deref().map(str::as_bytes) {
                ObservedResource::Before
            } else {
                ObservedResource::Unknown
            },
        )
    }
}


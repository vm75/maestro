pub fn render_quadlet(
    config: &Config,
    id: &str,
    base: &Path,
    fingerprint: &str,
) -> Result<BTreeMap<String, String>> {
    render_quadlet_at(config, id, base, base, fingerprint)
}

/// Private environment files are relative to the authoritative YAML directory.
pub fn render_quadlet_at(
    config: &Config,
    id: &str,
    base: &Path,
    private_base: &Path,
    fingerprint: &str,
) -> Result<BTreeMap<String, String>> {
    ensure!(base.is_absolute(), "Quadlet storage base must be absolute");
    ensure!(
        private_base.is_absolute(),
        "Quadlet private file base must be absolute"
    );
    ensure!(
        super::id_valid(id) && super::store::valid_revision(fingerprint),
        "invalid Quadlet resource identity"
    );
    let mut config = config.clone();
    config.validate()?;
    let service = config
        .services
        .get(id)
        .ok_or_else(|| anyhow!("unknown Quadlet service"))?;
    ensure!(
        is_quadlet(service),
        "resource is not a Podman Quadlet application"
    );
    super::compose::validate_options(service)?;
    let ownership = format!("{HEADER}\n# resource=service/{id}\n# fingerprint={fingerprint}\n");
    let network = format!("maestro-network-{}", &revision(id.as_bytes())[..24]);
    let mut files = BTreeMap::from([(
        format!("{network}.network"),
        format!(
            "{ownership}[Network]\nNetworkName={network}\nLabel=io.maestro.fingerprint={fingerprint}\n"
        ),
    )]);
    for (name, container) in &service.containers {
        let unit = unit_name(id, name);
        let mut body = format!("{ownership}[Unit]\nDescription=Maestro container {id}/{name}\n");
        for dependency in &service.depends_on {
            let target = &config.services[dependency];
            ensure!(
                is_quadlet(target),
                "Quadlet dependencies must also use Quadlet"
            );
            for member in target.containers.keys() {
                add_dependency(&mut body, &unit_name(dependency, member))?;
            }
        }
        for member in container.depends_on.keys() {
            add_dependency(&mut body, &unit_name(id, member))?;
        }
        if let Some(peer) = container.network_mode.strip_prefix("service:") {
            if !container.depends_on.contains_key(peer) {
                add_dependency(&mut body, &unit_name(id, peer))?;
            }
        }
        writeln!(body, "\n[Container]")?;
        writeln!(body, "Image={}", scalar(&container.image)?)?;
        let native_name = if container.container_name.is_empty() {
            &unit
        } else {
            &container.container_name
        };
        ensure!(
            native_name
                .as_bytes()
                .first()
                .is_some_and(u8::is_ascii_alphanumeric)
                && native_name
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || b"_.-".contains(&byte)),
            "invalid native container name"
        );
        writeln!(body, "ContainerName={native_name}")?;
        match container.network_mode.as_str() {
            "" => writeln!(body, "Network={network}.network\nNetworkAlias={name}")?,
            "host" | "none" => writeln!(body, "Network={}", container.network_mode)?,
            mode => {
                let peer = mode
                    .strip_prefix("service:")
                    .ok_or_else(|| anyhow!("unsupported Quadlet network mode"))?;
                writeln!(body, "Network={}.container", unit_name(id, peer))?;
            }
        }
        writeln!(
            body,
            "Label=io.maestro.service={id}\nLabel=io.maestro.container={name}\nLabel=io.maestro.fingerprint={fingerprint}"
        )?;
        options::render(&mut body, container)?;
        if service.containers.values().any(|dependent| {
            dependent
                .depends_on
                .get(name)
                .is_some_and(|condition| condition == "healthy")
        }) {
            writeln!(body, "Notify=healthy")?;
        }
        if container.read_only {
            writeln!(body, "ReadOnly=true")?;
        }
        if container.init {
            writeln!(body, "RunInit=true")?;
        }
        if container.memory_mib > 0 {
            writeln!(body, "PodmanArgs=--memory={}m", container.memory_mib)?;
        }
        if !container.working_dir.is_empty() {
            ensure!(
                super::path_valid(&container.working_dir, true),
                "invalid container working directory"
            );
            writeln!(body, "WorkingDir={}", scalar(&container.working_dir)?)?;
        }
        for port in &container.ports {
            ensure!(valid_port(port), "invalid Quadlet port mapping");
            writeln!(body, "PublishPort={port}")?;
        }
        for (key, value) in &container.environment {
            ensure!(valid_env(key), "invalid container environment name");
            writeln!(body, "Environment={}", word(&format!("{key}={value}"))?)?;
        }
        for reference in &container.env_files {
            let path = private_base.join(&config.secrets[reference]);
            writeln!(
                body,
                "EnvironmentFile={}",
                scalar(
                    path.to_str()
                        .ok_or_else(|| anyhow!("non-UTF-8 private file path"))?
                )?
            )?;
        }
        for mount in &container.mounts {
            let storage = &config.storage[&mount.storage];
            let path = base.join(&storage.path);
            let path = if mount.path.is_empty() {
                path
            } else {
                path.join(&mount.path)
            };
            let source = path
                .to_str()
                .ok_or_else(|| anyhow!("non-UTF-8 mount source"))?;
            ensure!(
                !source.contains(':')
                    && !mount.target.contains(':')
                    && matches!(mount.kind.as_str(), "" | "bind" | "directory" | "file")
                    && matches!(mount.selinux.as_str(), "" | "z" | "Z" | "private" | "shared"),
                "unsupported Quadlet mount"
            );
            let mut options = vec![if mount.read_only { "ro" } else { "rw" }];
            match mount.selinux.as_str() {
                "private" | "Z" => options.push("Z"),
                "shared" | "z" => options.push("z"),
                _ => {}
            }
            if mount.chown {
                options.push("U");
            }
            writeln!(
                body,
                "Volume={}",
                scalar(&format!("{source}:{}:{}", mount.target, options.join(",")))?
            )?;
        }
        if !container.command.is_empty() {
            let words = container
                .command
                .iter()
                .map(|arg| word(&arg.replace('$', "$$")))
                .collect::<Result<Vec<_>>>()?;
            writeln!(body, "Exec={}", words.join(" "))?;
        }
        let restart = match container.restart.as_str() {
            "" | "on-failure" => "on-failure",
            "always" | "unless-stopped" => "always",
            "no" => "no",
            _ => return Err(anyhow!("unsupported Quadlet restart policy")),
        };
        writeln!(body, "\n[Service]\nRestart={restart}\nRestartSec=5\nTimeoutStartSec=900")?;
        let stop = super::container_health::stop_seconds(&container.stop_grace_period)
            .ok_or_else(|| anyhow!("Quadlet stop grace period exceeds native timeout range"))?;
        let stop = if stop == 0 { 90 } else { u64::from(stop) + 30 };
        writeln!(body, "TimeoutStopSec={stop}")?;
        if container.cpus > 0 {
            writeln!(body, "CPUQuota={}%", i128::from(container.cpus) * 100)?;
        }
        if service.enabled {
            writeln!(body, "\n[Install]\nWantedBy=default.target")?;
        }
        files.insert(format!("{unit}.container"), body);
    }
    Ok(files)
}

fn is_quadlet(service: &super::Service) -> bool {
    service.kind == "container" && service.engine == "podman" && service.backend == "quadlet"
}

/// Return the unique declared owner of an exact generated application unit.
/// Network units and ambiguous names are intentionally not actionable.
pub fn managed_unit_owner<'a>(config: &'a Config, unit: &str) -> Option<&'a str> {
    let mut owners = config.services.iter().filter(|(id, service)| {
        if is_quadlet(service) {
            service.containers.keys().any(|member| {
                format!("{}.service", unit_name(id, member)) == unit
            })
        } else {
            service.kind == "container"
                && service.backend == "compose"
                && matches!(service.engine.as_str(), "podman" | "docker")
                && super::compose::boot_unit(id) == unit
        }
    });
    let (owner, _) = owners.next()?;
    if owners.next().is_some() {
        return None;
    }
    Some(owner.as_str())
}

/// Names emitted by Maestro's Quadlet and Compose generators are reserved
/// for the declarative coordinator, including units left behind by a prior apply.
pub fn managed_unit(unit: &str) -> bool {
    let Some(stem) = unit
        .strip_prefix("maestro-")
        .and_then(|unit| unit.strip_suffix(".service"))
    else {
        return false;
    };
    if stem.strip_prefix("compose-").is_some_and(super::id_valid) {
        return true;
    }
    let hex = |value: &str, width: usize| {
        value.len() == width
            && value
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
    };
    if let Some(hash) = stem
        .strip_prefix("network-")
        .and_then(|stem| stem.strip_suffix("-network"))
    {
        return hex(hash, 24);
    }
    stem.rsplit_once('-')
        .is_some_and(|(service, hash)| super::id_valid(service) && hex(hash, 16))
}

fn unit_name(service: &str, member: &str) -> String {
    format!(
        "maestro-{service}-{}",
        &revision(format!("{service}/{member}").as_bytes())[..16]
    )
}

fn add_dependency(body: &mut String, unit: &str) -> Result<()> {
    writeln!(body, "Requires={unit}.service\nAfter={unit}.service")?;
    Ok(())
}

fn scalar(value: &str) -> Result<String> {
    ensure!(
        value.trim() == value && !value.contains('\\') && !value.chars().any(char::is_control),
        "unsupported characters in Quadlet scalar"
    );
    Ok(value.replace('%', "%%"))
}

fn word(value: &str) -> Result<String> {
    ensure!(
        !value.chars().any(char::is_control),
        "unsupported control character in Quadlet argument"
    );
    Ok(serde_json::to_string(&value.replace('%', "%%"))?)
}

fn valid_port(value: &str) -> bool {
    let (ports, protocol) = value.split_once('/').unwrap_or((value, "tcp"));
    let parse = |part: &str| {
        part.parse::<u16>().is_ok_and(|port| port > 0)
            && part.bytes().all(|byte| byte.is_ascii_digit())
    };
    matches!(protocol, "tcp" | "udp")
        && match ports.split_once(':') {
            Some((host, guest)) => parse(host) && parse(guest),
            None => parse(ports),
        }
}

fn valid_env(value: &str) -> bool {
    value
        .as_bytes()
        .first()
        .is_some_and(|byte| byte.is_ascii_alphabetic() || *byte == b'_')
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
}


const HEADER: &str = "# Generated by Maestro from the authoritative workload configuration.";

pub fn render_quadlet(
    config: &Config,
    id: &str,
    base: &Path,
    fingerprint: &str,
) -> Result<BTreeMap<String, String>> {
    ensure!(base.is_absolute(), "Quadlet storage base must be absolute");
    ensure!(
        super::id_valid(id) && super::store::valid_revision(fingerprint),
        "invalid Quadlet resource identity"
    );
    let mut config = config.clone();
    config.validate()?;
    let service = config
        .services
        .get(id)
        .ok_or_else(|| anyhow!("unknown Quadlet service"))?;
    ensure!(
        is_quadlet(service),
        "resource is not a Podman Quadlet application"
    );
    let ownership = format!("{HEADER}\n# resource=service/{id}\n# fingerprint={fingerprint}\n");
    let network = format!("maestro-network-{}", &revision(id.as_bytes())[..24]);
    let mut files = BTreeMap::from([(
        format!("{network}.network"),
        format!(
            "{ownership}[Network]\nNetworkName={network}\nLabel=io.maestro.fingerprint={fingerprint}\n"
        ),
    )]);
    for (name, container) in &service.containers {
        reject_unrendered_options(container)?;
        let unit = unit_name(id, name);
        let mut body = format!("{ownership}[Unit]\nDescription=Maestro container {id}/{name}\n");
        for dependency in &service.depends_on {
            let target = &config.services[dependency];
            ensure!(
                is_quadlet(target),
                "Quadlet dependencies must also use Quadlet"
            );
            for member in target.containers.keys() {
                add_dependency(&mut body, &unit_name(dependency, member))?;
            }
        }
        for (member, condition) in &container.depends_on {
            ensure!(
                condition == "started",
                "Quadlet dependency condition is unsupported"
            );
            add_dependency(&mut body, &unit_name(id, member))?;
        }
        writeln!(body, "\n[Container]")?;
        writeln!(body, "Image={}", scalar(&container.image)?)?;
        let native_name = if container.container_name.is_empty() {
            &unit
        } else {
            &container.container_name
        };
        ensure!(
            native_name
                .as_bytes()
                .first()
                .is_some_and(u8::is_ascii_alphanumeric)
                && native_name
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || b"_.-".contains(&byte)),
            "invalid native container name"
        );
        writeln!(body, "ContainerName={native_name}")?;
        match container.network_mode.as_str() {
            "" => writeln!(body, "Network={network}.network\nNetworkAlias={name}")?,
            "host" | "none" => writeln!(body, "Network={}", container.network_mode)?,
            _ => return Err(anyhow!("unsupported Quadlet network mode")),
        }
        writeln!(
            body,
            "Label=io.maestro.service={id}\nLabel=io.maestro.container={name}\nLabel=io.maestro.fingerprint={fingerprint}"
        )?;
        writeln!(body, "NoNewPrivileges=true")?;
        if container.read_only {
            writeln!(body, "ReadOnly=true")?;
        }
        if container.init {
            writeln!(body, "RunInit=true")?;
        }
        if container.memory_mib > 0 {
            writeln!(body, "PodmanArgs=--memory={}m", container.memory_mib)?;
        }
        if container.cpus > 0 {
            writeln!(body, "PodmanArgs=--cpus={}", container.cpus)?;
        }
        if !container.working_dir.is_empty() {
            ensure!(
                super::path_valid(&container.working_dir, true),
                "invalid container working directory"
            );
            writeln!(body, "WorkingDir={}", scalar(&container.working_dir)?)?;
        }
        for port in &container.ports {
            ensure!(valid_port(port), "invalid Quadlet port mapping");
            writeln!(body, "PublishPort={port}")?;
        }
        for (key, value) in &container.environment {
            ensure!(valid_env(key), "invalid container environment name");
            writeln!(body, "Environment={}", word(&format!("{key}={value}"))?)?;
        }
        for reference in &container.env_files {
            let path = base.join(&config.secrets[reference]);
            writeln!(
                body,
                "EnvironmentFile={}",
                scalar(
                    path.to_str()
                        .ok_or_else(|| anyhow!("non-UTF-8 private file path"))?
                )?
            )?;
        }
        for mount in &container.mounts {
            let storage = &config.storage[&mount.storage];
            let path = base.join(&storage.path);
            let path = if mount.path.is_empty() {
                path
            } else {
                path.join(&mount.path)
            };
            let source = path
                .to_str()
                .ok_or_else(|| anyhow!("non-UTF-8 mount source"))?;
            ensure!(
                !source.contains(':')
                    && !mount.target.contains(':')
                    && matches!(mount.kind.as_str(), "" | "bind" | "directory" | "file")
                    && matches!(mount.selinux.as_str(), "" | "z" | "Z"),
                "unsupported Quadlet mount"
            );
            let mut options = vec![if mount.read_only { "ro" } else { "rw" }];
            if !mount.selinux.is_empty() {
                options.push(&mount.selinux);
            }
            if mount.chown {
                options.push("U");
            }
            writeln!(
                body,
                "Volume={}",
                scalar(&format!("{source}:{}:{}", mount.target, options.join(",")))?
            )?;
        }
        if !container.command.is_empty() {
            let words = container
                .command
                .iter()
                .map(|arg| word(&arg.replace('$', "$$")))
                .collect::<Result<Vec<_>>>()?;
            writeln!(body, "Exec={}", words.join(" "))?;
        }
        let restart = match container.restart.as_str() {
            "" | "on-failure" => "on-failure",
            "always" | "unless-stopped" => "always",
            "no" => "no",
            _ => return Err(anyhow!("unsupported Quadlet restart policy")),
        };
        writeln!(body, "\n[Service]\nRestart={restart}")?;
        if service.enabled {
            writeln!(body, "\n[Install]\nWantedBy=default.target")?;
        }
        files.insert(format!("{unit}.container"), body);
    }
    Ok(files)
}

fn is_quadlet(service: &super::Service) -> bool {
    service.kind == "container" && service.engine == "podman" && service.backend == "quadlet"
}

/// Names emitted by Maestro's Quadlet generator are reserved for the
/// declarative coordinator, including units left behind by a prior apply.
pub fn managed_unit(unit: &str) -> bool {
    let Some(stem) = unit
        .strip_prefix("maestro-")
        .and_then(|unit| unit.strip_suffix(".service"))
    else {
        return false;
    };
    let hex = |value: &str, width: usize| {
        value.len() == width
            && value
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
    };
    if let Some(hash) = stem
        .strip_prefix("network-")
        .and_then(|stem| stem.strip_suffix("-network"))
    {
        return hex(hash, 24);
    }
    stem.rsplit_once('-')
        .is_some_and(|(service, hash)| super::id_valid(service) && hex(hash, 16))
}

fn unit_name(service: &str, member: &str) -> String {
    format!(
        "maestro-{service}-{}",
        &revision(format!("{service}/{member}").as_bytes())[..16]
    )
}

fn add_dependency(body: &mut String, unit: &str) -> Result<()> {
    writeln!(body, "Requires={unit}.service\nAfter={unit}.service")?;
    Ok(())
}

fn scalar(value: &str) -> Result<String> {
    ensure!(
        value.trim() == value && !value.contains('\\') && !value.chars().any(char::is_control),
        "unsupported characters in Quadlet scalar"
    );
    Ok(value.replace('%', "%%"))
}

fn word(value: &str) -> Result<String> {
    ensure!(
        !value.chars().any(char::is_control),
        "unsupported control character in Quadlet argument"
    );
    Ok(serde_json::to_string(&value.replace('%', "%%"))?)
}

fn valid_port(value: &str) -> bool {
    let (ports, protocol) = value.split_once('/').unwrap_or((value, "tcp"));
    let parse = |part: &str| {
        part.parse::<u16>().is_ok_and(|port| port > 0)
            && part.bytes().all(|byte| byte.is_ascii_digit())
    };
    matches!(protocol, "tcp" | "udp")
        && match ports.split_once(':') {
            Some((host, guest)) => parse(host) && parse(guest),
            None => parse(ports),
        }
}

fn valid_env(value: &str) -> bool {
    value
        .as_bytes()
        .first()
        .is_some_and(|byte| byte.is_ascii_alphabetic() || *byte == b'_')
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_')
}

fn reject_unrendered_options(container: &Container) -> Result<()> {
    let unsupported = !container.entrypoint.is_empty()
        || !container.user.is_empty()
        || !container.userns_mode.is_empty()
        || !container.uid_maps.is_empty()
        || !container.gid_maps.is_empty()
        || !container.group_add.is_empty()
        || !container.devices.is_empty()
        || !container.cap_add.is_empty()
        || !container.cap_drop.is_empty()
        || !container.security_opt.is_empty()
        || container.privileged
        || container.tty
        || !container.tmpfs.is_empty()
        || !container.shm_size.is_empty()
        || !container.stop_grace_period.is_empty()
        || !container.pull_policy.is_empty()
        || !container.log_driver.is_empty()
        || !container.log_options.is_empty()
        || container.healthcheck.is_some();
    ensure!(
        !unsupported,
        "workload specifies a Quadlet option that cannot yet be rendered"
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const FIXTURE: &str = r#"
version: 1
storage:
  cache: {path: volumes/cache}
secrets:
  settings: private/env
services:
  demo:
    kind: container
    enabled: true
    containers:
      backend: {image: docker.io/library/redis:7}
      web:
        image: docker.io/library/alpine:latest
        depends_on: {backend: started}
        command: ["echo", "literal ${VALUE} 100%"]
        environment: {SETTING: "two words"}
        env_files: [settings]
        mounts: [{storage: cache, target: /cache, read_only: true}]
        ports: ["8080:80"]
"#;

    #[test]
    fn deterministic_generation_and_safe_directives() {
        let configuration = super::super::parse(FIXTURE.as_bytes()).unwrap();
        let fingerprint = revision(FIXTURE.as_bytes());
        let base = Path::new("/tmp/quadlet-test");
        let files = render_quadlet(&configuration, "demo", base, &fingerprint).unwrap();
        assert_eq!(
            files,
            render_quadlet(&configuration, "demo", base, &fingerprint).unwrap()
        );
        assert_eq!(files.len(), 3);
        let body = &files[&format!("{}.container", unit_name("demo", "web"))];
        assert!(body.contains(&format!(
            "Requires={}.service",
            unit_name("demo", "backend")
        )));
        assert!(body.contains("Exec=\"echo\" \"literal $${VALUE} 100%%\""));
        assert!(body.contains("Environment=\"SETTING=two words\""));
        assert!(body.contains("EnvironmentFile=/tmp/quadlet-test/private/env"));
        assert!(body.contains("Volume=/tmp/quadlet-test/volumes/cache:/cache:ro"));
        assert!(body.contains("[Install]\nWantedBy=default.target"));
        assert!(body.contains(&format!("# fingerprint={fingerprint}")));

        let disabled = super::super::parse(
            FIXTURE
                .replace("enabled: true", "enabled: false")
                .as_bytes(),
        )
        .unwrap();
        assert!(
            render_quadlet(&disabled, "demo", base, &fingerprint)
                .unwrap()
                .values()
                .all(|file| !file.contains("[Install]"))
        );
    }

    #[test]
    fn unsupported_and_injected_fields_are_rejected() {
        let mut configuration = super::super::parse(FIXTURE.as_bytes()).unwrap();
        let fingerprint = revision(FIXTURE.as_bytes());
        let base = Path::new("/tmp/quadlet-test");
        let container = configuration
            .services
            .get_mut("demo")
            .unwrap()
            .containers
            .get_mut("web")
            .unwrap();
        container
            .environment
            .insert("BREAK".into(), "bad\n[Service]".into());
        assert!(render_quadlet(&configuration, "demo", base, &fingerprint).is_err());
        let container = configuration
            .services
            .get_mut("demo")
            .unwrap()
            .containers
            .get_mut("web")
            .unwrap();
        container.environment.clear();
        container.privileged = true;
        assert!(render_quadlet(&configuration, "demo", base, &fingerprint).is_err());
    }

    #[test]
    #[ignore = "requires the native Podman Quadlet generator"]
    fn native_generator_accepts_rootless_artifacts() {
        let temp = tempfile::tempdir().unwrap();
        let configuration = super::super::parse(FIXTURE.as_bytes()).unwrap();
        let files = render_quadlet(
            &configuration,
            "demo",
            temp.path(),
            &revision(FIXTURE.as_bytes()),
        )
        .unwrap();
        for (name, contents) in files {
            std::fs::write(temp.path().join(name), contents).unwrap();
        }
        let generator = std::env::var_os("MAESTRO_QUADLET_GENERATOR")
            .unwrap_or_else(|| "/usr/lib/podman/quadlet".into());
        let output = std::process::Command::new(generator)
            .args(["-user", "-dryrun", "-no-kmsg-log"])
            .env("QUADLET_UNIT_DIRS", temp.path())
            .output()
            .unwrap();
        let stdout = String::from_utf8_lossy(&output.stdout);
        assert!(
            output.status.success(),
            "{}",
            String::from_utf8_lossy(&output.stderr)
        );
        assert!(
            stdout.contains(&format!("{}.service", unit_name("demo", "web"))),
            "{stdout}"
        );
        let label = format!("io.maestro.fingerprint={}", revision(FIXTURE.as_bytes()));
        assert!(stdout.matches(&label).count() >= 3, "{stdout}");
        assert!(stdout.contains("default.target"), "{stdout}");
    }
}

use std::{
    fmt::Write,
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Result, ensure};

use crate::core::declarative::{
    ApplyProvider, Change, Config, ObservedResource, Operation, RecoveryProvider, Share,
};

const SAMBA_HEADER: &str = "# Generated by Maestro for Samba shares.\n";
const NFS_HEADER: &str = "# Generated by Maestro for NFS exports.\n";

pub fn render_samba(
    shares: &std::collections::BTreeMap<String, Share>,
    storage_base: &Path,
) -> Result<String> {
    let mut out = String::from(SAMBA_HEADER);
    for (id, share) in shares {
        if !share.enabled || share.protocol == "nfs" {
            continue;
        }
        let path = if share.path.is_empty() {
            storage_base.join(id)
        } else {
            storage_base.join(&share.path)
        };
        writeln!(out, "\n[{id}]")?;
        writeln!(out, "  path = {}", path.display())?;
        writeln!(
            out,
            "  read only = {}",
            if share.read_only { "yes" } else { "no" }
        )?;
        writeln!(
            out,
            "  browseable = {}",
            if share.browseable { "yes" } else { "no" }
        )?;
        writeln!(
            out,
            "  guest ok = {}",
            if share.guest { "yes" } else { "no" }
        )?;
        if !share.users.is_empty() {
            writeln!(out, "  valid users = {}", share.users.join(" "))?;
        }
    }
    Ok(out)
}

pub fn render_nfs(
    shares: &std::collections::BTreeMap<String, Share>,
    storage_base: &Path,
) -> Result<String> {
    let mut out = String::from(NFS_HEADER);
    for (id, share) in shares {
        if !share.enabled || share.protocol == "samba" {
            continue;
        }
        let path = if share.path.is_empty() {
            storage_base.join(id)
        } else {
            storage_base.join(&share.path)
        };
        let ro = if share.read_only { "ro" } else { "rw" };
        let squash = if share.root_squash == Some(false) {
            "no_root_squash"
        } else {
            "root_squash"
        };
        let clients = if share.clients.is_empty() {
            vec!["*".to_string()]
        } else {
            share.clients.clone()
        };
        let specs: Vec<_> = clients
            .iter()
            .map(|c| format!("{c}({ro},sync,{squash},no_subtree_check)"))
            .collect();
        writeln!(out, "{} {}", path.display(), specs.join(" "))?;
    }
    Ok(out)
}

pub struct ShareProvider {
    pub samba_conf: PathBuf,
    pub exports_file: PathBuf,
    pub storage_base: PathBuf,
}

impl ShareProvider {
    pub fn new(samba_conf: PathBuf, exports_file: PathBuf, storage_base: PathBuf) -> Self {
        Self {
            samba_conf,
            exports_file,
            storage_base,
        }
    }
}

impl ApplyProvider for ShareProvider {
    async fn preflight(&self, change: &Change, _previous: &Config, desired: &Config) -> Result<()> {
        let Some(share_id) = change.resource.strip_prefix("share/") else {
            return Ok(());
        };
        if let Some(share) = desired.shares.get(share_id) {
            ensure!(super::id_valid(share_id), "invalid share ID");
            if !share.storage.is_empty() {
                ensure!(
                    desired.storage.contains_key(&share.storage),
                    "referenced storage not found"
                );
            }
        }
        Ok(())
    }

    async fn apply(&self, change: &Change, _previous: &Config, desired: &Config) -> Result<()> {
        if !change.resource.starts_with("share/") {
            return Ok(());
        }
        let samba_content = render_samba(&desired.shares, &self.storage_base)?;
        if let Some(parent) = self.samba_conf.parent() {
            let _ = fs::create_dir_all(parent);
        }
        fs::write(&self.samba_conf, samba_content)?;

        let nfs_content = render_nfs(&desired.shares, &self.storage_base)?;
        if let Some(parent) = self.exports_file.parent() {
            let _ = fs::create_dir_all(parent);
        }
        fs::write(&self.exports_file, nfs_content)?;
        Ok(())
    }
}

impl RecoveryProvider for ShareProvider {
    async fn observe(
        &self,
        change: &Change,
        _previous: &Config,
        _desired: &Config,
    ) -> Result<ObservedResource> {
        if !change.resource.starts_with("share/") {
            return Ok(ObservedResource::Unknown);
        }
        if !self.samba_conf.exists() && !self.exports_file.exists() {
            return if change.operation == Operation::Create {
                Ok(ObservedResource::Before)
            } else {
                Ok(ObservedResource::After)
            };
        }
        Ok(ObservedResource::After)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::declarative::Share;
    use std::collections::BTreeMap;

    #[test]
    fn test_render_samba_and_nfs() {
        let mut shares = BTreeMap::new();
        shares.insert(
            "media".to_string(),
            Share {
                guest: true,
                browseable: true,
                root_squash: Some(false),
                security: "user".to_string(),
                protocol: "both".to_string(),
                storage: "".to_string(),
                path: "media".to_string(),
                enabled: true,
                read_only: false,
                users: vec!["admin".to_string()],
                clients: vec!["192.168.1.0/24".to_string()],
            },
        );
        let base = Path::new("/var/storage");
        let smb = render_samba(&shares, base).unwrap();
        assert!(smb.contains("[media]"));
        assert!(smb.contains("path = /var/storage/media"));
        assert!(smb.contains("guest ok = yes"));
        assert!(smb.contains("valid users = admin"));

        let nfs = render_nfs(&shares, base).unwrap();
        assert!(nfs.contains("/var/storage/media"));
        assert!(nfs.contains("192.168.1.0/24(rw,sync,no_root_squash,no_subtree_check)"));
    }
}

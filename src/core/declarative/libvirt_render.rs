//! Managed Libvirt XML, translated from the reference implementation libvirt_render.go.
//! Compare managed hardware rather than daemon-generated aliases/addresses.
use super::{Config, plan::service_fingerprint, store};
use anyhow::{Result, anyhow, ensure};
use quick_xml::{
    Reader,
    events::{BytesStart, Event},
};
use std::{collections::BTreeMap, path::Path};

pub(super) const NS: &str = "https://maestro.local/managed/v1";
pub(super) fn domain_name(id: &str) -> String {
    format!("maestro-{id}")
}
pub(super) fn runtime_fingerprint(config: &Config, id: &str) -> Result<String> {
    let mut copy = config.clone();
    let service = copy
        .services
        .get_mut(id)
        .ok_or_else(|| anyhow!("unknown VM"))?;
    service.enabled = false;
    service.name.clear();
    service.description.clear();
    service_fingerprint(&copy, id)
}
fn machine_valid(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= 128
        && s.as_bytes()[0].is_ascii_alphanumeric()
        && s.bytes()
            .all(|b| b.is_ascii_alphanumeric() || b"_.-".contains(&b))
}
fn machine_matches(want: &str, actual: &str) -> bool {
    want == actual
        || (want == "q35"
            && actual.starts_with("pc-q35-")
            && actual.len() > 7
            && machine_valid(actual))
}
pub(super) fn render(config: &Config, id: &str, base: &Path) -> Result<String> {
    use std::fmt::Write;
    let mut config = config.clone();
    config.validate()?;
    ensure!(
        super::id_valid(id) && base.is_absolute(),
        "invalid Libvirt resource or storage base"
    );
    let service = config
        .services
        .get(id)
        .ok_or_else(|| anyhow!("unknown Libvirt VM"))?;
    ensure!(
        service.kind == "vm" && service.backend == "libvirt",
        "resource is not a Libvirt VM"
    );
    let vm = service
        .vm
        .as_ref()
        .ok_or_else(|| anyhow!("VM identity unavailable"))?;
    ensure!(
        !vm.uuid.is_empty() && !vm.mac.is_empty(),
        "persistent VM identity is required"
    );
    ensure!(
        vm.image.is_empty() && vm.root_size_gib == 0,
        "Libvirt initial images/root size require explicit disk provisioning"
    );
    ensure!(
        vm.pool.is_empty() && vm.project.is_empty(),
        "Libvirt existing-disk definitions do not use Incus pool/project bindings"
    );
    ensure!(
        (1..=26).contains(&vm.disks.len()),
        "provision declared disk storage before defining the guest; maximum 26 disks"
    );
    ensure!(
        vm.firmware.is_empty() || vm.firmware == "bios",
        "this Libvirt adapter requires BIOS; UEFI support is pending"
    );
    let arch = if vm.architecture.is_empty() {
        "x86_64"
    } else {
        &vm.architecture
    };
    ensure!(arch == "x86_64", "unsupported Libvirt guest architecture");
    let machine = if vm.machine.is_empty() {
        "q35"
    } else {
        &vm.machine
    };
    ensure!(machine_valid(machine), "invalid Libvirt machine type");
    ensure!(
        service.depends_on.is_empty(),
        "Libvirt boot dependency integration is not implemented"
    );
    let fingerprint = service_fingerprint(&config, id)?;
    let runtime = runtime_fingerprint(&config, id)?;
    let esc = |s: &str| quick_xml::escape::escape(s).into_owned();
    let mut xml = format!(
        concat!(
            "<!-- Generated by maestro; edit the authoritative workload configuration. -->\n",
            "<domain type=\"kvm\">\n  <name>{}</name>\n  <uuid>{}</uuid>\n",
            "  <metadata><managed xmlns=\"{}\" id=\"{}\" fingerprint=\"{}\" runtime=\"{}\"/></metadata>\n",
            "  <memory unit=\"MiB\">{}</memory>\n  <vcpu>{}</vcpu>\n",
            "  <os><type arch=\"{}\" machine=\"{}\">hvm</type><boot dev=\"hd\"/></os>\n",
            "  <features><acpi/><apic/></features>\n  <cpu mode=\"host-model\"/>\n",
            "  <on_poweroff>destroy</on_poweroff>\n  <on_reboot>restart</on_reboot>\n  <on_crash>destroy</on_crash>\n  <devices>\n"
        ),
        domain_name(id),
        vm.uuid,
        NS,
        id,
        fingerprint,
        runtime,
        vm.memory_mib,
        vm.cpus,
        arch,
        machine
    );
    for (i, reference) in vm.disks.iter().enumerate() {
        let disk = config
            .storage
            .get(reference)
            .ok_or_else(|| anyhow!("missing VM disk reference"))?;
        ensure!(
            disk.kind == "file" && matches!(disk.format.as_str(), "qcow2" | "raw"),
            "VM disks require an explicit qcow2 or raw format"
        );
        let path = base.join(&disk.path);
        let path = path
            .to_str()
            .filter(|p| !p.chars().any(char::is_control))
            .ok_or_else(|| anyhow!("invalid VM disk path"))?;
        writeln!(
            xml,
            "    <disk type=\"file\" device=\"disk\"><driver name=\"qemu\" type=\"{}\"/><source file=\"{}\"/><target dev=\"vd{}\" bus=\"virtio\"/></disk>",
            disk.format,
            esc(path),
            (b'a' + i as u8) as char
        )?;
    }
    let binding = &config.bindings[&vm.network];
    ensure!(
        matches!(binding.kind.as_str(), "network" | "bridge"),
        "unsupported Libvirt network binding"
    );
    writeln!(
        xml,
        "    <interface type=\"{}\"><mac address=\"{}\"/><source {}=\"{}\"/><model type=\"virtio\"/></interface>",
        binding.kind,
        vm.mac,
        binding.kind,
        esc(&binding.name)
    )?;
    xml.push_str("    <video><model type=\"vga\"/></video>\n    <console type=\"pty\"><target type=\"serial\" port=\"0\"/></console>\n  </devices>\n</domain>\n");
    Ok(xml)
}

// A bounded XML reader. Namespace declarations are scoped to the element
// where they appear, so a foreign marker cannot pass by reusing a prefix.
#[derive(Default, Debug)]
struct Node {
    name: String,
    ns: String,
    attrs: BTreeMap<String, String>,
    text: String,
    children: Vec<Node>,
}
impl Node {
    fn child(&self, name: &str) -> Result<&Node> {
        let mut children = self.children.iter().filter(|n| n.name == name);
        let child = children
            .next()
            .ok_or_else(|| anyhow!("missing XML field {name}"))?;
        ensure!(children.next().is_none(), "ambiguous XML field {name}");
        Ok(child)
    }
    fn attr(&self, key: &str) -> &str {
        self.attrs.get(key).map(String::as_str).unwrap_or("")
    }
    fn value(&self, key: &str) -> Result<&str> {
        Ok(self.child(key)?.text.trim())
    }
}
fn start(
    e: &BytesStart<'_>,
    parent: Option<&BTreeMap<String, String>>,
) -> Result<(Node, BTreeMap<String, String>)> {
    let mut scope = parent.cloned().unwrap_or_default();
    let mut attrs = BTreeMap::new();
    for attr in e.attributes() {
        let attr = attr?;
        let key = std::str::from_utf8(attr.key.as_ref())?.to_owned();
        let val = attr.unescape_value()?.into_owned();
        if key == "xmlns" {
            scope.insert(String::new(), val);
        } else if let Some(prefix) = key.strip_prefix("xmlns:") {
            scope.insert(prefix.into(), val);
        } else {
            ensure!(attrs.insert(key, val).is_none(), "duplicate XML attribute");
        }
    }
    let q = e.name();
    let raw = std::str::from_utf8(q.as_ref())?;
    let (prefix, name) = raw.split_once(':').unwrap_or(("", raw));
    let ns = scope.get(prefix).cloned().unwrap_or_default();
    ensure!(
        prefix.is_empty() || scope.contains_key(prefix),
        "unbound XML namespace"
    );
    Ok((
        Node {
            name: name.into(),
            ns,
            attrs,
            ..Default::default()
        },
        scope,
    ))
}
fn parse_xml(xml: &[u8]) -> Result<Node> {
    ensure!(
        xml.len() <= super::MAX_CONFIG_BYTES,
        "Libvirt XML exceeds 1 MiB"
    );
    let mut reader = Reader::from_reader(xml);
    let mut stack: Vec<(Node, BTreeMap<String, String>)> = Vec::new();
    let mut root = None;
    let mut count = 0;
    fn push(
        node: Node,
        stack: &mut [(Node, BTreeMap<String, String>)],
        root: &mut Option<Node>,
    ) -> Result<()> {
        if let Some((parent, _)) = stack.last_mut() {
            parent.children.push(node);
        } else {
            ensure!(root.is_none(), "multiple XML roots");
            *root = Some(node);
        }
        Ok(())
    }
    loop {
        match reader.read_event()? {
            Event::Start(e) => {
                count += 1;
                ensure!(
                    count <= 16384 && stack.len() < 64,
                    "XML structure exceeds limit"
                );
                let n = start(&e, stack.last().map(|(_, s)| s))?;
                stack.push(n);
            }
            Event::Empty(e) => {
                count += 1;
                ensure!(count <= 16384, "XML structure exceeds limit");
                let (node, _) = start(&e, stack.last().map(|(_, s)| s))?;
                push(node, &mut stack, &mut root)?;
            }
            Event::End(_) => {
                let (node, _) = stack.pop().ok_or_else(|| anyhow!("unbalanced XML"))?;
                push(node, &mut stack, &mut root)?;
            }
            Event::Text(e) => {
                let value = quick_xml::escape::unescape(std::str::from_utf8(e.as_ref())?)?;
                if let Some((node, _)) = stack.last_mut() {
                    node.text.push_str(&value);
                } else {
                    ensure!(value.trim().is_empty(), "unexpected text outside XML root");
                }
            }
            Event::GeneralRef(e) => {
                let raw = std::str::from_utf8(e.as_ref())?;
                let entity = format!("&{raw};");
                let value = quick_xml::escape::unescape(&entity)?;
                let (node, _) = stack
                    .last_mut()
                    .ok_or_else(|| anyhow!("unexpected XML entity"))?;
                node.text.push_str(&value);
            }
            Event::CData(e) => {
                let (node, _) = stack
                    .last_mut()
                    .ok_or_else(|| anyhow!("unexpected XML CDATA"))?;
                node.text.push_str(std::str::from_utf8(e.as_ref())?);
            }
            Event::DocType(_) => return Err(anyhow!("XML DTD is unsupported")),
            Event::Eof => break,
            _ => {}
        }
    }
    ensure!(stack.is_empty(), "incomplete XML");
    root.ok_or_else(|| anyhow!("missing XML root"))
}

#[derive(Debug, PartialEq, Eq)]
struct Disk {
    kind: String,
    device: String,
    driver: String,
    format: String,
    file: String,
    target: String,
    bus: String,
}
#[derive(Debug, PartialEq, Eq)]
struct Interface {
    kind: String,
    mac: String,
    network: String,
    bridge: String,
    model: String,
}
#[derive(Debug, PartialEq, Eq)]
pub(super) struct Domain {
    pub id: String,
    pub uuid: String,
    pub name: String,
    pub fingerprint: String,
    pub runtime: String,
    kind: String,
    memory: i64,
    cpus: i64,
    arch: String,
    machine: String,
    os: String,
    boot: String,
    disks: Vec<Disk>,
    interface: Interface,
    video: String,
}
impl Domain {
    pub(super) fn owned(&self, id: &str, uuid: &str) -> bool {
        self.id == id
            && self.uuid == uuid
            && self.name == domain_name(id)
            && store::valid_revision(&self.fingerprint)
            && store::valid_revision(&self.runtime)
    }
    pub(super) fn hardware_matches(&self, actual: &Self) -> bool {
        let a = &self.interface;
        let b = &actual.interface;
        let interface = a.kind == b.kind
            && a.mac == b.mac
            && a.network == b.network
            && a.model == b.model
            && (a.bridge == b.bridge || (a.kind == "network" && a.bridge.is_empty()));
        self.uuid == actual.uuid
            && self.name == actual.name
            && self.kind == actual.kind
            && self.memory == actual.memory
            && self.cpus == actual.cpus
            && self.arch == actual.arch
            && machine_matches(&self.machine, &actual.machine)
            && self.os == actual.os
            && self.boot == actual.boot
            && self.disks == actual.disks
            && interface
            && self.video == actual.video
    }
}
pub(super) fn parse_domain(xml: &[u8]) -> Result<Domain> {
    let root = parse_xml(xml)?;
    ensure!(
        root.name == "domain" && root.ns.is_empty(),
        "invalid Libvirt domain XML"
    );
    let marker = root.child("metadata")?.child("managed")?;
    ensure!(
        marker.ns == NS,
        "Libvirt domain is not owned by this managed definition"
    );
    let memory = root.child("memory")?;
    let amount = memory.text.trim().parse::<i64>()?;
    let memory = match memory.attr("unit") {
        "MiB" | "mib" => amount,
        "" | "KiB" | "kib" => {
            ensure!(amount % 1024 == 0, "non-integral guest memory");
            amount / 1024
        }
        _ => return Err(anyhow!("unsupported native memory unit")),
    };
    let os = root.child("os")?;
    let typ = os.child("type")?;
    let dev = root.child("devices")?;
    let mut disks = Vec::new();
    for disk in dev.children.iter().filter(|n| n.name == "disk") {
        let driver = disk.child("driver")?;
        let source = disk.child("source")?;
        let target = disk.child("target")?;
        disks.push(Disk {
            kind: disk.attr("type").into(),
            device: disk.attr("device").into(),
            driver: driver.attr("name").into(),
            format: driver.attr("type").into(),
            file: source.attr("file").into(),
            target: target.attr("dev").into(),
            bus: target.attr("bus").into(),
        });
    }
    let nic = dev.child("interface")?;
    let source = nic.child("source")?;
    let interface = Interface {
        kind: nic.attr("type").into(),
        mac: nic.child("mac")?.attr("address").into(),
        network: source.attr("network").into(),
        bridge: source.attr("bridge").into(),
        model: nic.child("model")?.attr("type").into(),
    };
    let video = dev.child("video")?.child("model")?.attr("type").into();
    ensure!(
        !dev.children.iter().any(|n| n.name == "graphics"),
        "unexpected graphical listener in managed headless guest"
    );
    Ok(Domain {
        id: marker.attr("id").into(),
        uuid: root.value("uuid")?.into(),
        name: root.value("name")?.into(),
        fingerprint: marker.attr("fingerprint").into(),
        runtime: marker.attr("runtime").into(),
        kind: root.attr("type").into(),
        memory,
        cpus: root.value("vcpu")?.parse()?,
        arch: typ.attr("arch").into(),
        machine: typ.attr("machine").into(),
        os: typ.text.trim().into(),
        boot: os.child("boot")?.attr("dev").into(),
        disks,
        interface,
        video,
    })
}
// Private XML is capture evidence only. Refuse state outside the supported
// BIOS/standalone disk profile, including native extensions and backing chains.
pub(super) fn validate_backup_xml(raw: &[u8], want: &Domain) -> Result<()> {
    let actual = parse_domain(raw)?;
    ensure!(
        want.hardware_matches(&actual)
            && want.id == actual.id
            && want.fingerprint == actual.fingerprint
            && want.runtime == actual.runtime,
        "private Libvirt XML does not match managed identity/hardware"
    );
    let root = parse_xml(raw)?;
    fn guard(node: &Node, parent: &str) -> Result<()> {
        if parent != "metadata" {
            ensure!(
                node.ns.is_empty() && node.attrs.keys().all(|key| !key.contains(':')),
                "unsupported Libvirt XML extension"
            );
        }
        ensure!(
            !matches!(
                node.name.as_str(),
                "loader"
                    | "nvram"
                    | "varstore"
                    | "kernel"
                    | "initrd"
                    | "dtb"
                    | "tpm"
                    | "filesystem"
                    | "hostdev"
                    | "shmem"
                    | "crypto"
                    | "launchSecurity"
                    | "sysinfo"
                    | "commandline"
                    | "encryption"
                    | "dataStore"
                    | "memoryBacking"
            ),
            "Libvirt guest has unsupported state dependencies"
        );
        if node.name == "memory" {
            ensure!(
                parent == "domain",
                "additional memory device needs explicit capture support"
            );
        }
        if node.name == "backingStore" {
            ensure!(
                node.attrs.is_empty() && node.children.is_empty(),
                "Libvirt backing chain requires explicit capture support"
            );
        }
        if node.name == "source" && parent == "disk" {
            ensure!(
                node.attrs
                    .keys()
                    .all(|key| matches!(key.as_str(), "file" | "index" | "startupPolicy"))
                    && node.children.iter().all(|n| n.name == "seclabel"),
                "unsupported Libvirt disk source"
            );
        }
        if matches!(node.name.as_str(), "serial" | "console") {
            ensure!(
                matches!(node.attr("type"), "pty" | "null"),
                "external serial/console dependency"
            );
        }
        if node.name == "metadata" {
            ensure!(
                node.children.len() == 1 && node.children[0].name == "managed",
                "additional private native metadata needs review"
            );
            return Ok(());
        }
        for child in &node.children {
            guard(child, &node.name)?;
        }
        Ok(())
    }
    guard(&root, "")?;
    Ok(())
}

pub(super) fn valid_kvm_capabilities(xml: &[u8]) -> bool {
    parse_xml(xml).is_ok_and(|root| {
        root.name == "domainCapabilities"
            && root.ns.is_empty()
            && root.value("domain").is_ok_and(|s| s == "kvm")
            && root.value("arch").is_ok_and(|s| s == "x86_64")
            && root
                .value("machine")
                .is_ok_and(|s| machine_matches("q35", s))
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    fn fixture() -> Config {
        super::super::parse(
            br#"version: 1
storage:
  root: {kind: file, format: qcow2, path: "disk & data.qcow2"}
bindings:
  lan: {kind: network, name: default}
services:
  guest:
    kind: vm
    backend: libvirt
    vm:
      uuid: "c3d699a2-921d-4009-8b63-1d0144fbb7dc"
      mac: "52:54:00:12:34:56"
      cpus: 2
      memory_mib: 1024
      network: lan
      disks: [root]
"#,
        )
        .unwrap()
    }
    #[test]
    fn native_hardware_comparison_and_ownership() {
        let c = fixture();
        let xml = render(&c, "guest", Path::new("/storage")).unwrap();
        assert!(xml.contains("disk &amp; data.qcow2"));
        assert!(!xml.contains("<graphics"));
        let want = parse_domain(xml.as_bytes()).unwrap();
        assert!(want.owned("guest", &c.services["guest"].vm.as_ref().unwrap().uuid));
        let live = xml
            .replace("unit=\"MiB\">1024", "unit=\"KiB\">1048576")
            .replace("machine=\"q35\"", "machine=\"pc-q35-9.0\"")
            .replace(
                "network=\"default\"",
                "network=\"default\" bridge=\"virbr0\"",
            );
        assert!(want.hardware_matches(&parse_domain(live.as_bytes()).unwrap()));
        assert!(
            !want.hardware_matches(
                &parse_domain(
                    live.replace("network=\"default\"", "network=\"other\"")
                        .as_bytes()
                )
                .unwrap()
            )
        );
        assert!(!want.hardware_matches(
            &parse_domain(xml.replace("type=\"vga\"", "type=\"virtio\"").as_bytes()).unwrap()
        ));
        assert!(parse_domain(xml.replace(NS, "https://foreign.invalid/").as_bytes()).is_err());
        let mut next = c.clone();
        next.services.get_mut("guest").unwrap().enabled = true;
        assert_eq!(
            runtime_fingerprint(&c, "guest").unwrap(),
            runtime_fingerprint(&next, "guest").unwrap()
        );
        assert_ne!(
            service_fingerprint(&c, "guest").unwrap(),
            service_fingerprint(&next, "guest").unwrap()
        );
    }
    #[test]
    fn private_backup_xml_rejects_unsupported_guest_state() {
        let config = fixture();
        let raw = render(&config, "guest", Path::new("/storage")).unwrap();
        let want = parse_domain(raw.as_bytes()).unwrap();
        assert!(validate_backup_xml(raw.as_bytes(), &want).is_ok());
        for altered in [
            raw.replace("</os>","<nvram>/var/lib/guest.fd</nvram></os>"),
            raw.replace("</disk>","<backingStore type=\"file\"><source file=\"/disk/base\"/></backingStore></disk>"),
            raw.replace("</devices>","<tpm model=\"tpm-crb\"/></devices>"),
            raw.replace("</domain>","<qemu:commandline xmlns:qemu=\"http://libvirt.org/schemas/domain/qemu/1.0\"/></domain>"),
        ]{assert!(validate_backup_xml(altered.as_bytes(),&want).is_err());}
    }
    #[test]
    fn capability_contract() {
        assert!(valid_kvm_capabilities(b"<domainCapabilities><domain>kvm</domain><arch>x86_64</arch><machine>pc-q35-9.0</machine></domainCapabilities>"));
        assert!(!valid_kvm_capabilities(b"<domainCapabilities><domain>qemu</domain><arch>x86_64</arch><machine>q35</machine></domainCapabilities>"));
        assert!(!valid_kvm_capabilities(b"<domainCapabilities><domain>kvm</domain><arch>x86_64</arch><machine>q35</machine></domainCapabilities><extra/>"));
    }
}
